"""Real-process controls for the generated upstream pymdp candidate bundle."""

from __future__ import annotations

import ast
import shutil
import subprocess
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SCRIPT = PROJECT_ROOT / "scripts" / "generate_pymdp_sparse_patch.py"
PROJECT_PYTHON = PROJECT_ROOT / ".venv" / "bin" / "python"
PATCH_NAME = "0001-feat-sparse-B-support-in-Agent-and-FPI.patch"
DESCRIPTION_NAME = "PR_DESCRIPTION.md"
PATCHED_FILES = {"pymdp/utils.py", "pymdp/control.py", "pymdp/agent.py"}
PROBE = PROJECT_ROOT / "scripts" / "probe_pymdp_sparse.py"

#: The bundle generator runs in a real subprocess that imports jax and pymdp
#: from cold caches, and the repository's 60 s default is sized for in-process
#: unit tests. The inner probe-worker timeout (240 s in
#: scripts/probe_pymdp_sparse.py) stays strictly below this mark so the child
#: is the one that reports a hang, with its output attached.
pytestmark = pytest.mark.timeout(900)


def _pymdp_runtime_replacements(source: str) -> list[str]:
    """Return pymdp objects replaced directly, through aliases, or via setattr."""

    tree = ast.parse(source)
    aliases: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            aliases.update(
                alias.asname or alias.name.split(".", 1)[0]
                for alias in node.names
                if alias.name == "pymdp" or alias.name.startswith("pymdp.")
            )
        elif isinstance(node, ast.ImportFrom) and node.module is not None:
            if node.module == "pymdp" or node.module.startswith("pymdp."):
                aliases.update(alias.asname or alias.name for alias in node.names)

    def dependency_expression(node: ast.AST) -> bool:
        if isinstance(node, ast.Name):
            return node.id in aliases
        if isinstance(node, ast.Attribute):
            return dependency_expression(node.value)
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            return (
                node.func.id in {"getattr", "vars"}
                and bool(node.args)
                and dependency_expression(node.args[0])
            )
        return False

    # Propagate simple local aliases such as ``patched = utils``. Iterate because
    # an alias may be copied more than once before the replacement.
    changed = True
    while changed:
        changed = False
        for node in ast.walk(tree):
            if not isinstance(node, (ast.Assign, ast.AnnAssign)):
                continue
            value = node.value
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            if dependency_expression(value):
                for target in targets:
                    if isinstance(target, ast.Name) and target.id not in aliases:
                        aliases.add(target.id)
                        changed = True

    offenders: list[str] = []
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name)
            and node.func.id in {"setattr", "delattr"}
            and node.args
            and dependency_expression(node.args[0])
        ):
            offenders.append(f"{node.func.id}({ast.unparse(node.args[0])}, ...)")

        if isinstance(node, ast.Assign):
            targets = node.targets
        elif isinstance(node, (ast.AnnAssign, ast.AugAssign, ast.NamedExpr)):
            targets = [node.target]
        else:
            continue
        for target in targets:
            if (
                isinstance(target, ast.Attribute)
                and dependency_expression(target.value)
                or isinstance(target, ast.Subscript)
                and dependency_expression(target.value)
            ):
                offenders.append(ast.unparse(target))
    return offenders


def _run(bundle_dir: Path, *arguments: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [
            str(PROJECT_PYTHON),
            str(SCRIPT),
            *arguments,
            "--bundle-dir",
            str(bundle_dir),
        ],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True,
        check=False,
        timeout=600,
    )


@pytest.fixture(scope="module")
def generated_bundle(tmp_path_factory: pytest.TempPathFactory) -> Path:
    bundle = tmp_path_factory.mktemp("upstream-pymdp-bundle") / "candidate"
    generated = _run(bundle)
    assert generated.returncode == 0, generated.stdout + generated.stderr
    assert (bundle / PATCH_NAME).is_file()
    assert (bundle / DESCRIPTION_NAME).is_file()
    return bundle


def test_generate_then_check_accepts_both_current_bundle_entries(generated_bundle: Path):
    """POSITIVE CONTROL: independently regenerated bytes pass non-writing check."""
    checked = _run(generated_bundle, "--check")
    assert checked.returncode == 0, checked.stdout + checked.stderr
    assert "patch and PR description are current" in checked.stdout


def test_generated_patch_touches_exactly_the_three_analyzed_sites(generated_bundle: Path):
    text = (generated_bundle / PATCH_NAME).read_text(encoding="utf-8")
    touched = {
        line.split("/", 1)[1].split("\t", 1)[0].strip()
        for line in text.splitlines()
        if line.startswith("+++ b/")
    }
    assert touched == PATCHED_FILES


def test_generated_description_retains_limits_and_submission_state(generated_bundle: Path):
    text = (generated_bundle / DESCRIPTION_NAME).read_text(encoding="utf-8")
    assert "n_batch" in text
    assert "0.000e+00" in text
    assert "not submitted" in text.casefold()
    for limit in ("does not achieve", "no sparse path"):
        assert limit in text.casefold()


def test_equivalence_probe_cannot_replace_pymdp_functions_at_runtime():
    """The claimed result must come from the patched copy, not reassignment.

    NEGATIVE CONTROL: a planted replacement of the exact function the original
    probe replaced must be detected. This proves the structural guard can fail;
    the fresh-process equivalence test separately proves that the patch works.
    """

    source = PROBE.read_text(encoding="utf-8")
    assert _pymdp_runtime_replacements(source) == []

    planted_direct = source + "\nutils.validate_normalization = lambda *args: None\n"
    assert _pymdp_runtime_replacements(planted_direct) == ["utils.validate_normalization"]

    planted_import_alias = (
        source
        + "\nfrom pymdp import utils as patched_utils\n"
        + "patched_utils.validate_normalization = lambda *args: None\n"
    )
    assert "patched_utils.validate_normalization" in _pymdp_runtime_replacements(
        planted_import_alias
    )

    planted_local_alias = source + "\npatched_utils = utils\nsetattr(patched_utils, 'x', None)\n"
    assert "setattr(patched_utils, ...)" in _pymdp_runtime_replacements(planted_local_alias)


def test_git_apply_gate_rejects_planted_invented_context(
    generated_bundle: Path,
    tmp_path: Path,
):
    """NEGATIVE CONTROL: the apply gate itself can reject a malformed patch."""
    import pymdp

    staged = tmp_path / "staged"
    staged.mkdir()
    shutil.copytree(Path(pymdp.__file__).resolve().parent, staged / "pymdp")
    subprocess.run(["git", "init", "-q", "."], cwd=staged, check=True)
    broken = staged / "broken.patch"
    broken.write_text(
        (generated_bundle / PATCH_NAME)
        .read_text(encoding="utf-8")
        .replace("    sums = jnp.sum", "    sums = jnp.total"),
        encoding="utf-8",
    )

    rejected = subprocess.run(
        ["git", "apply", "--check", "-p1", str(broken)],
        cwd=staged,
        capture_output=True,
        text=True,
        check=False,
    )

    assert rejected.returncode != 0, "git apply accepted the planted invalid context"


@pytest.mark.parametrize("stale_name", (PATCH_NAME, DESCRIPTION_NAME))
def test_check_rejects_each_planted_stale_bundle_entry(
    generated_bundle: Path,
    tmp_path: Path,
    stale_name: str,
):
    """NEGATIVE CONTROLS: neither shipped file can drift behind a green check."""
    planted = tmp_path / "candidate"
    shutil.copytree(generated_bundle, planted)
    target = planted / stale_name
    target.write_bytes(target.read_bytes() + b"\nplanted stale bytes\n")

    checked = _run(planted, "--check")

    assert checked.returncode == 1, checked.stdout + checked.stderr
    assert stale_name in checked.stderr
    other = DESCRIPTION_NAME if stale_name == PATCH_NAME else PATCH_NAME
    assert other not in checked.stderr, (
        "the check reported both entries stale when only one was changed; "
        "the byte comparisons are not independent"
    )
